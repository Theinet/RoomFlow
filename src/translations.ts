export type Language = 'en' | 'uk';
export function translate(key: string, language: Language, ...values: unknown[]): string {
  const template = language === 'en' ? english[key] ?? key : key;
  return template.replace(/\{(\d+)\}/g, (match, index) => values[Number(index)] === undefined ? match : String(values[Number(index)]));
}

// Notifications are persisted in Ukrainian; only their presentation is localized.
const notificationPatterns = Object.keys(english).filter(key => key.startsWith('Зустріч «')).map(key => ({
  key,
  pattern: new RegExp('^' + key.split(/\{\d+\}/).map(part => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('(.*?)') + '$'),
}));
export function translateMessage(message: string, language: Language): string {
  if (language === 'uk') return message;
  if (english[message]) return english[message];
  for (const { key, pattern } of notificationPatterns) {
    const match = pattern.exec(message);
    if (match) return translate(key, language, ...match.slice(1).map(value => english[value] ?? value));
  }
  return message;
}

const feedbackKeys = Object.keys(english).filter(key => key.startsWith('Зустріч «') || key.startsWith('Створено серію з'));
const escapePattern = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const feedbackPatterns = feedbackKeys.flatMap(key => ([key, english[key]]).map(template => ({
  key, pattern: new RegExp('^' + template.split(/\{\d+\}/).map(escapePattern).join('(.*?)') + '$'),
})));
const reverseEnglish = Object.fromEntries(Object.entries(english).map(([key, value]) => [value, key]));

/** Re-localize already displayed system feedback after a language change. */
export function translateFeedback(message: string, language: Language): string {
  return message.split('\n').map(line => {
    const key = reverseEnglish[line] ?? line;
    if (english[key]) return translate(key, language);
    for (const {key: template, pattern} of feedbackPatterns) {
      const match = pattern.exec(line);
      if (match) return translate(template, language, ...match.slice(1).map(value => translate(reverseEnglish[value] ?? value, language)));
    }
    return line;
  }).join('\n');
}
